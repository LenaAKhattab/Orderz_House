#!/usr/bin/env node
// Generates the app's English tables from the translation memory.
//
//   node tool/i18n/generate.mjs            # write lib/core/i18n/*.dart + backend push table
//   node tool/i18n/generate.mjs --check    # fail (exit 1) when a tr()/trf() key has no English
//
// Inputs (tracked):
//   tool/i18n/translations_en.json   Arabic source → English (UI strings + server strings)
//   tool/i18n/server_strings.json    Arabic strings / templates emitted by backend/src ({0} = ${…})
//   tool/i18n/supplement_en.json     manual additions / overrides (wins over the memory)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '../..');
const repo = path.resolve(app, '../..');
const check = process.argv.includes('--check');

const load = (f, d) => (fs.existsSync(path.join(here, f)) ? JSON.parse(fs.readFileSync(path.join(here, f), 'utf8')) : d);
const memory = { ...load('translations_en.json', {}), ...load('supplement_en.json', {}) };
const serverStrings = load('server_strings.json', []);

// Consistent product terminology across batches.
const NORMALIZE = [[/\bPantry House\b/g, 'Pantry']];
const en = (k) => {
  let v = memory[k];
  if (v == null) return null;
  for (const [re, rep] of NORMALIZE) v = v.replace(re, rep);
  return v;
};

// ---- scan lib for tr('…') / trf('…', …) keys (single-quoted, adjacent pieces allowed)
const unescape = (s) => s.replace(/\\(.)/g, (_, c) => ({ n: '\n', t: '\t', r: '\r' }[c] ?? c));
const keyRe = /\btrf?\(\s*((?:'(?:[^'\\\n]|\\.)*'\s*)+)/g;
const pieceRe = /'((?:[^'\\\n]|\\.)*)'/g;
const appKeys = new Map();
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (p.endsWith('.dart') && !/\/core\/i18n\/(i18n|strings_en|server_strings_en|server_text)\.dart$/.test(p.replace(/\\/g, '/'))) {
      const src = fs.readFileSync(p, 'utf8');
      let m;
      while ((m = keyRe.exec(src))) {
        let key = '';
        let pm;
        pieceRe.lastIndex = 0;
        while ((pm = pieceRe.exec(m[1]))) key += unescape(pm[1]);
        if (!appKeys.has(key)) appKeys.set(key, path.relative(app, p).replace(/\\/g, '/'));
      }
    }
  }
})(path.join(app, 'lib'));

const missing = [...appKeys.keys()].filter((k) => en(k) == null);
const AR = /[؀-ۿ]/;
const badValues = [...appKeys.keys()].filter((k) => en(k) != null && AR.test(en(k)));
const placeholderIssues = [...appKeys.keys()].filter((k) => {
  const v = en(k);
  if (v == null) return false;
  return (k.match(/\{\d+\}/g) || []).some((ph) => !v.includes(ph));
});
if (missing.length || badValues.length || placeholderIssues.length) {
  for (const k of missing) console.error(`MISSING  ${appKeys.get(k)}  ${JSON.stringify(k)}`);
  for (const k of badValues) console.error(`ARABIC   ${appKeys.get(k)}  ${JSON.stringify(k)}`);
  for (const k of placeholderIssues) console.error(`PLACEHOLDER ${appKeys.get(k)}  ${JSON.stringify(k)}`);
  console.error(`\n${missing.length} missing, ${badValues.length} with Arabic, ${placeholderIssues.length} placeholder issues`);
  process.exit(1);
}
if (check) {
  console.log(`OK: ${appKeys.size} app keys translated`);
  process.exit(0);
}

// ---- emit Dart
const dartStr = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;
const appEntries = [...appKeys.keys()].sort().map((k) => `  ${dartStr(k)}: ${dartStr(en(k))},`);
fs.writeFileSync(
  path.join(app, 'lib/core/i18n/strings_en.dart'),
  `// GENERATED by tool/i18n/generate.mjs — English translations keyed by the Arabic source string.\n` +
    `// Do not edit by hand; edit tool/i18n/*.json and regenerate.\n\n` +
    `const Map<String, String> appStringsEn = {\n${appEntries.join('\n')}\n};\n`,
);

const exact = [], templates = [], serverJson = { exact: {}, templates: [] };
for (const s of [...new Set(serverStrings)].sort()) {
  const v = en(s);
  if (v == null || AR.test(v)) continue;
  if (/\{\d+\}/.test(s)) {
    if ((s.match(/\{\d+\}/g) || []).every((ph) => v.includes(ph)) && s.replace(/\{\d+\}/g, '').trim().length >= 4) {
      templates.push(`  ServerTemplate(${dartStr(s)}, ${dartStr(v)}),`);
      serverJson.templates.push([s, v]);
    }
  } else {
    exact.push(`  ${dartStr(s)}: ${dartStr(v)},`);
    serverJson.exact[s] = v;
  }
}
// Templates with more literal text first, so the most specific pattern wins.
templates.sort((a, b) => b.length - a.length);
serverJson.templates.sort((a, b) => b[0].replace(/\{\d+\}/g, '').length - a[0].replace(/\{\d+\}/g, '').length);
fs.writeFileSync(
  path.join(app, 'lib/core/i18n/server_strings_en.dart'),
  `// GENERATED by tool/i18n/generate.mjs — English for server-authored Arabic text. Do not edit by hand.\n` +
    `import 'server_text.dart';\n\n` +
    `const Map<String, String> serverStringsEn = {\n${exact.join('\n')}\n};\n\n` +
    `const List<ServerTemplate> serverTemplatesEn = [\n${templates.join('\n')}\n];\n`,
);
const backendOut = path.join(repo, 'backend/src/i18n/serverStringsEn.json');
fs.mkdirSync(path.dirname(backendOut), { recursive: true });
fs.writeFileSync(backendOut, JSON.stringify(serverJson) + '\n');
console.log(`app keys ${appKeys.size}; server exact ${exact.length}, templates ${templates.length}`);
