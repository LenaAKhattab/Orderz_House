#!/usr/bin/env node
/**
 * Generate src/locales/<de|nl|ro>/index.js — the single lazy chunk per new locale (all namespaces).
 * Namespaces come from the canonical English catalog, so a new namespace is never forgotten.
 * `--check` exits 1 when an index is missing or stale (used by tests / prebuild).
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const LOCALES_DIR = join(HERE, "../../src/locales");
export const LAZY_LOCALES = ["de", "nl", "ro"];

export function namespaces() {
  return readdirSync(join(LOCALES_DIR, "en"))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.replace(/\.json$/, ""))
    .sort();
}

export function renderIndex(locale) {
  const ns = namespaces();
  const ident = (n) => `ns_${n}`;
  return [
    "// GENERATED by scripts/i18n/generateLocaleIndex.mjs — do not edit by hand.",
    `// One lazy chunk with every UI namespace for "${locale}" (loaded by src/i18n/loadLocaleBundle.js).`,
    ...ns.map((n) => `import ${ident(n)} from "./${n}.json";`),
    "",
    "export default {",
    ...ns.map((n) => `  ${n}: ${ident(n)},`),
    "};",
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const loc of LAZY_LOCALES) {
    const file = join(LOCALES_DIR, loc, "index.js");
    const next = renderIndex(loc);
    const cur = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (cur === next) continue;
    if (check) {
      console.error(`stale or missing: src/locales/${loc}/index.js`);
      stale += 1;
    } else {
      writeFileSync(file, next);
      console.log(`wrote src/locales/${loc}/index.js (${namespaces().length} namespaces)`);
    }
  }
  if (check && stale) process.exitCode = 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
